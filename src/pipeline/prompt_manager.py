    def create_custom_prompt(self, template: str, **kwargs) -> str:
        """支持模板化、动态插值的自定义提示词生成"""
        try:
            return template.format(**kwargs)
        except KeyError as e:
            raise ValueError(f"模板插值变量 {e} 未完整提供")